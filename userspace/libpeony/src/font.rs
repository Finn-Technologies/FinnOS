#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn advances_are_proportional() {
        assert!(glyph_advance('i') < glyph_advance('m'));
        assert!(glyph_advance(' ') < glyph_advance('W'));
        assert!(title_advance('i') < title_advance('W'));
        let expected =
            u32::from(lookup_text('H').advance) + u32::from(lookup_text('i').advance) + 4;
        assert_eq!(text_width("Hi!"), expected);
        assert_eq!(text_width(""), 0);
        assert!(title_width("Settings") > text_width("Settings"));
    }

    #[test]
    fn bearings_place_caps_above_baseline() {
        let h = lookup_text('H');
        assert!(h.y_off < 0, "cap top must sit above the baseline");
        assert!(h.x_off >= 0);
        let g = lookup_text('g');
        let bottom = i32::from(g.y_off) + i32::from(g.h);
        assert!(bottom > 0, "descender must drop below the baseline");
        let dot = lookup_text('.');
        assert!(dot.h <= 4);
    }

    #[test]
    fn coverage_decodes_full_range() {
        let h = lookup_text('H');
        let mut seen_solid = false;
        let mut seen_empty = false;
        for row in 0..u32::from(h.h) {
            for col in 0..u32::from(h.w) {
                let a = glyph_coverage(&TEXT_DATA, h, row, col);
                if a > 200 {
                    seen_solid = true;
                }
                if a == 0 {
                    seen_empty = true;
                }
            }
        }
        assert!(seen_solid && seen_empty);
        // Out-of-bounds reads are transparent.
        assert_eq!(glyph_coverage(&TEXT_DATA, h, 99, 99), 0);
    }

    #[test]
    fn unsupported_chars_fall_back_to_question() {
        assert_eq!(lookup_text('\u{0}').ch, '?');
        assert_eq!(lookup_text('\u{1F}').ch, '?');
        assert_eq!(lookup_text('\u{4E2D}').ch, '?');
        assert_eq!(lookup_text('\u{2026}').ch, '\u{2026}');
        assert_eq!(lookup_text('A').ch, 'A');
    }
}
