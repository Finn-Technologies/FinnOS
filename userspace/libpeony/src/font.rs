//! Real Instrument Sans proportional anti-aliased font atlas.
//!
//! Embedded 4-bit alpha coverage bitmaps rasterized from Instrument Sans
//! (Google Fonts, SIL Open Font License 1.1) at 4x supersampling with LANCZOS
//! downsampling. Two optical sizes: 16px UI text and 20px titles.
//!
//! - `#![no_std]` compatible, integer math only (no floating point).
//! - Decode is a nibble lookup (`alpha = nibble * 17`); blending reuses
//!   [`crate::canvas::Canvas::set_pixel_coverage`].
//! - Baseline layout: pen `y_top` is the top of the ascender box; the glyph
//!   ink origin is `(pen_x + x_off, pen_y_baseline + y_off)` where
//!   `pen_y_baseline = y_top + ASCENT`.
//! - Coverage: ASCII 32..=126 plus ellipsis (U+2026) and bullet (U+2022).
//!   Anything else falls back to `?`.
//!
//! Regeneration: `python3 /tmp/peonywork/gen_font.py` (needs Pillow and
//! `InstrumentSans.ttf`), then `python3 /tmp/peonywork/assemble_font.py`.

#![allow(clippy::unreadable_literal, clippy::cast_possible_truncation)]

/// Legacy cell width kept for layout approximations (advance unit floor).
pub const FONT_WIDTH: usize = 8;
/// Legacy cell height; equals [`TEXT_ASCENT`].
pub const FONT_HEIGHT: usize = 16;

/// Line pitch for 16px UI text.
pub const LINE_HEIGHT_BODY: u32 = TEXT_LINE;
/// Line pitch for 20px titles.
pub const LINE_HEIGHT_TITLE: u32 = TITLE_LINE;

/// UI text size selector.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum FontSize {
    /// 16px UI text.
    Text,
    /// 20px titles.
    Title,
}

/// Index of `c` into a 97-entry glyph table (ASCII 32..=126, then … •).
const fn table_index(c: char) -> usize {
    let code = c as u32;
    if code >= 32 && code <= 126 {
        (code - 32) as usize
    } else if c == '\u{2026}' {
        95
    } else if c == '\u{2022}' {
        96
    } else {
        // `?` fallback (index 31).
        31
    }
}

/// Look up the 16px glyph for `c` (falls back to `?`).
#[must_use]
pub fn lookup_text(c: char) -> &'static Glyph {
    &TEXT_GLYPHS[table_index(c)]
}

/// Look up the 20px glyph for `c` (falls back to `?`).
#[must_use]
pub fn lookup_title(c: char) -> &'static Glyph {
    &TITLE_GLYPHS[table_index(c)]
}

/// Pen advance of `c` at 16px.
#[must_use]
pub fn glyph_advance(c: char) -> usize {
    lookup_text(c).advance as usize
}

/// Pen advance of `c` at 20px.
#[must_use]
pub fn title_advance(c: char) -> usize {
    lookup_title(c).advance as usize
}

/// Pixel-accurate width of a string at 16px.
#[must_use]
pub fn text_width(text: &str) -> u32 {
    let mut w: u32 = 0;
    for c in text.chars() {
        if c == '\n' {
            continue;
        }
        w = w.saturating_add(glyph_advance(c) as u32);
    }
    w
}

/// Pixel-accurate width of a string at 20px.
#[must_use]
pub fn title_width(text: &str) -> u32 {
    let mut w: u32 = 0;
    for c in text.chars() {
        if c == '\n' {
            continue;
        }
        w = w.saturating_add(title_advance(c) as u32);
    }
    w
}

/// Decode 0..=255 alpha coverage for glyph pixel (`row`, `col`).
///
/// `blob` is the matching size blob; pixels pack high-nibble-first.
#[must_use]
pub fn glyph_coverage(blob: &[u8], g: &Glyph, row: u32, col: u32) -> u8 {
    if row >= u32::from(g.h) || col >= u32::from(g.w) {
        return 0;
    }
    let bit = (row * u32::from(g.w) + col) as usize;
    let byte = blob[g.data as usize + bit / 2];
    let nibble = if bit.is_multiple_of(2) {
        byte >> 4
    } else {
        byte & 0x0F
    };
    nibble * 17
}

/// A rasterized proportional glyph.
#[derive(Clone, Copy, Debug)]
pub struct Glyph {
    /// Source character.
    pub ch: char,
    /// Pen advance in pixels.
    pub advance: u8,
    /// Bitmap width.
    pub w: u8,
    /// Bitmap height.
    pub h: u8,
    /// Ink left minus pen x (may be negative).
    pub x_off: i8,
    /// Ink top minus baseline (<= 0).
    pub y_off: i8,
    /// Byte offset into the size blob (2 px per byte, high nibble first).
    pub data: u32,
}

